/**
 * @file    wcwidth.c
 * @brief   码点宽度表与字素簇列数计算（表由 Unicode 16.0 数据生成）
 *
 * 表的来源与不变式：
 *   · zero[]  = 类别 Mn/Me/Mc/Cf 的并集，减去 U+00AD（软连字符按 1 列），
 *               再加上 Hangul Jamo 元音/终声 U+1160..U+11FF、Emoji 肤色
 *               修饰符 U+1F3FB..U+1F3FF、Tag 字符 U+E0020..U+E007F。
 *   · wide[]  = East_Asian_Width ∈ {W, F} 且已分配（category != Cn）的并集，
 *               并剔除 U+1160..U+11FF（它们按零宽处理，见上）。
 *   · 两张表都按 first 升序、区间互不重叠 —— 二分查找的前提。
 *   表由宿主 Python 3 的 unicodedata（Unicode 16.0.0）离线生成后内联；
 *   不引入生成期依赖，也不在启动时建表。
 *
 * 为什么把 Mc（占位组合符）也算零宽：终端无法把梵文/泰文的元音符号
 * 单独画在下一格，把它当独立字符会撕裂字形并让退格删半个音节。
 * 这是终端显示语义，不是 Unicode 类别语义，故写在这里而不是 utf8.c。
 *
 * 性能：二分查找 335/130 个区间，最坏 ~9 次比较；utf8_strwidth 对每个
 * 簇只做一次首码点查表，组合符不再重复查 wide[]。
 */

