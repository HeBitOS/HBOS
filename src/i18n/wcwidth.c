static int bisearch(uint32_t cp, const i18n_cp_range_t *tab, uint32_t count)
{
    if (count == 0 || cp < tab[0].first || cp > tab[count - 1].last) return 0;
    uint32_t lo = 0, hi = count - 1;
    while (lo <= hi) {
        uint32_t mid = lo + (hi - lo) / 2;
        if (cp > tab[mid].last) lo = mid + 1;
        else if (cp < tab[mid].first) hi = mid - 1;
        else return 1;
    }
    return 0;
}

int i18n_cp_is_extend(uint32_t cp)
{
    return bisearch(cp, zero_ranges, sizeof(zero_ranges) / sizeof(zero_ranges[0]));
}

int i18n_cp_is_regional_indicator(uint32_t cp)
{
    return cp >= 0x1F1E6 && cp <= 0x1F1FF;
}

int utf8_wcwidth(uint32_t cp)
{
    if (cp == 0) return 0;                       /* NUL 不占列（与 glibc 一致） */
    if (cp < 0x20 || (cp >= 0x7F && cp < 0xA0)) return -1;
    if (cp > 0x10FFFF) return -1;
    if (i18n_cp_is_extend(cp)) return UTF8_WCWIDTH_ZERO;
    if (bisearch(cp, wide_ranges, sizeof(wide_ranges) / sizeof(wide_ranges[0])))
        return UTF8_WCWIDTH_WIDE;
    return 1;
}

int utf8_cluster_width(const char *s, uint32_t len)
{
    if (!s || len == 0) return 0;

    uint32_t i = 0, cp = 0;
    int n = utf8_decode_fffd(s, len, &cp);
    if (n <= 0) return 1;
    i = (uint32_t)n;

    int width = utf8_wcwidth(cp);
    if (width < 0) width = 1;                    /* 控制字符在终端占 1 格 */
    if (i18n_cp_is_regional_indicator(cp)) width = 1;

    int emoji_presentation = 0;
    int zwj_join = 0;
    while (i < len) {
        uint32_t next = 0;
        int m = utf8_decode_fffd(s + i, len - i, &next);
        if (m <= 0) break;
        i += (uint32_t)m;
        if (next == 0xFE0F) emoji_presentation = 1;   /* VS16：文本→Emoji 呈现 */
        if (next == 0x200D) zwj_join = 1;
        if (i18n_cp_is_regional_indicator(next)) {
            width = 2;                                /* 国旗对占两列 */
            break;
        }
    }

    if (zwj_join) width = 2;                     /* ZWJ 序列整体按两列，不累加 */
    if (emoji_presentation && width < 2) width = 2;
    return width;
}

int utf8_strwidth(const char *s, uint32_t len)
{
    if (!s) return 0;
    uint32_t off = 0;
    int total = 0;
    while (off < len) {
        uint32_t next = utf8_cluster_next(s, len, off);
        if (next <= off) break;                  /* 防御：迭代必须前进 */
        total += utf8_cluster_width(s + off, next - off);
        off = next;
    }
    return total;
}
